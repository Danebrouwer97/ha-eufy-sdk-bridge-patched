#!/usr/bin/env python3
"""Write this app's config.yaml from the official app's config.yaml.

The patched app is the official one with a different name, slug and version, and without the
prebuilt `image:` (Home Assistant builds it from the Dockerfile here). Everything else, including
options, schema, ports, ingress and discovery, is copied unchanged, so new official options carry
over by themselves.

Usage: make-app-config.py <official config.yaml> <official version> <out config.yaml>
"""

import re
import sys

REPO = "https://github.com/Danebrouwer97/ha-eufy-sdk-bridge-patched"


def main(src: str, official_version: str, out: str) -> None:
    s = open(src, encoding="utf-8").read()

    def rep(pattern: str, new: str) -> None:
        nonlocal s
        s, n = re.subn(pattern, new, s, count=1, flags=re.M)
        if n != 1:
            sys.exit(f"official config.yaml changed shape: no match for {pattern!r}")

    rep(r"^name: .*$", "name: eufy-sdk bridge (patched)")
    rep(r"^version: .*$", f'version: "{official_version}-audio.1"')
    rep(r"^slug: .*$", "slug: eufy_sdk_bridge_patched")
    rep(
        r"^description: .*$",
        f"description: The official eufy-sdk bridge {official_version} plus live camera sound and "
        "push-to-talk. See the README.",
    )
    rep(r"^url: .*$", f'url: "{REPO}"')
    # Drop the prebuilt image (and the comment block above it) so Home Assistant builds the Dockerfile.
    rep(r"^(#[^\n]*\n)*image: .*\n", "# Built by Home Assistant from the Dockerfile here (official image + runtime.patch).\n")

    header = (
        "# Generated by scripts/make-app-config.py from the official eufy-sdk bridge app's config.yaml.\n"
        "# Only name, version, slug, description, url and the removed `image:` differ. Don't edit by hand.\n"
    )
    open(out, "w", encoding="utf-8").write(header + s)


if __name__ == "__main__":
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    main(*sys.argv[1:])
